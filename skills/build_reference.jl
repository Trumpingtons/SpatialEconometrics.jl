# ---------------------------------------------------------------------------
# Build the Claude skill's function reference from the package's docstrings.
#
#   julia --project=. skills/build_reference.jl           # write the files
#   julia --project=. skills/build_reference.jl --check   # exit 1 if stale
#
# Writes skills/spatial-econometrics/references/api/: one file per submodule,
# holding the raw docstring of every exported name defined there, plus
# INDEX.md, which maps each name to its file. The raw docstring text is used,
# not Julia's rendering of it, so the output is the same on every Julia
# version. Testset 45 of test/runtests.jl runs the check.
# ---------------------------------------------------------------------------

using SpatialEconometrics

const SE = SpatialEconometrics
const API_DIR = joinpath(@__DIR__, "spatial-econometrics", "references", "api")

const HEADER = "<!-- Generated by skills/build_reference.jl from the package's docstrings. " *
               "Do not edit: change the docstring and rerun the script. -->\n\n"

# Docstrings use `#` headings; inside the reference they sit under a `##`
# heading per name, so they are moved down two levels. Lines inside fenced
# code are left alone, since `#` there starts a Julia comment.
function demote_headings(text::AbstractString)
    out = String[]
    fenced = false
    for line in split(text, '\n')
        startswith(lstrip(line), "```") && (fenced = !fenced)
        push!(out, !fenced && startswith(line, "#") ? "##" * line : line)
    end
    return join(out, '\n')
end

docstring_text(d) = rstrip(lstrip(==('
'), join(string.(d.text))))

"""
    build_reference() -> Dict{String,String}

The reference files, keyed by file name.
"""
function build_reference()
    groups = Dict{Module,Vector{Symbol}}()
    external = Symbol[]
    for n in names(SE)
        n === :SpatialEconometrics && continue
        b = Base.Docs.Binding(SE, n)
        m = b.mod
        if m !== SE && parentmodule(m) !== SE
            push!(external, n)        # a re-export, documented by its own package
            continue
        end
        push!(get!(groups, m, Symbol[]), n)
    end

    files = Dict{String,String}()
    index = IOBuffer()
    print(index, HEADER)
    println(index, "# Function reference: index\n")
    println(index, "Every exported name, with the file that holds its docstring. ",
            "Grep this folder for a name, or open the file for its submodule.\n")
    for m in sort(collect(keys(groups)); by = string)
        short = m === SE ? "SpatialEconometrics" : string(nameof(m))
        fname = short * ".md"
        io = IOBuffer()
        print(io, HEADER)
        println(io, "# ", short, "\n")
        meta = Base.Docs.meta(m)
        for n in sort(groups[m]; by = string)
            md = meta[Base.Docs.Binding(m, n)]
            println(io, "## `", n, "`\n")
            for sig in md.order
                println(io, demote_headings(docstring_text(md.docs[sig])), "\n")
            end
        end
        files[fname] = String(take!(io))
        println(index, "- **", short, "** (`", fname, "`): ",
                join(("`" * string(n) * "`" for n in sort(groups[m]; by = string)), ", "))
    end
    isempty(external) ||
        println(index, "\nRe-exported from other packages, documented there: ",
                join(("`" * string(n) * "`" for n in sort(external; by = string)), ", "), ".")
    files["INDEX.md"] = String(take!(index))
    return files
end

"""
    stale_reference_files(dir = API_DIR) -> Vector{String}

The reference files that are missing, out of date, or no longer generated.
"""
function stale_reference_files(dir::AbstractString = API_DIR)
    files = build_reference()
    stale = [f for (f, s) in files if !isfile(joinpath(dir, f)) || read(joinpath(dir, f), String) != s]
    isdir(dir) && append!(stale, [f for f in readdir(dir) if endswith(f, ".md") && !haskey(files, f)])
    return sort(stale)
end

if abspath(PROGRAM_FILE) == @__FILE__
    if "--check" in ARGS
        stale = stale_reference_files()
        isempty(stale) && (println("reference is current"); exit(0))
        println("stale: ", join(stale, ", "), "\nrun: julia --project=. skills/build_reference.jl")
        exit(1)
    end
    mkpath(API_DIR)
    files = build_reference()
    for f in readdir(API_DIR)
        endswith(f, ".md") && !haskey(files, f) && rm(joinpath(API_DIR, f))
    end
    for (f, s) in files
        write(joinpath(API_DIR, f), s)
    end
    println("wrote ", length(files), " files to ", API_DIR)
end
